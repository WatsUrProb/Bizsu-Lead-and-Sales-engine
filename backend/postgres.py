"""Small SQLite-compatible adapter for a Supabase Postgres connection.

The application keeps SQLite for local development. On Vercel, DATABASE_URL
points to Supabase's transaction pooler and this adapter preserves the existing
query interface while using Postgres for all mutable records.
"""

from __future__ import annotations

import re
from urllib.parse import urlparse


class Row(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


class Result:
    def __init__(self, cursor, lastrowid=None):
        self.cursor = cursor
        self._lastrowid = lastrowid

    def fetchone(self):
        item = self.cursor.fetchone()
        return Row(item) if item is not None else None

    def fetchall(self):
        return [Row(item) for item in self.cursor.fetchall()]

    def __iter__(self):
        for item in self.cursor:
            yield Row(item)

    @property
    def lastrowid(self):
        return self._lastrowid


class Connection:
    def __init__(self, url: str):
        import psycopg
        from psycopg.rows import dict_row

        sslmode = "prefer" if urlparse(url).hostname in {"localhost", "127.0.0.1"} else "require"
        self.raw = psycopg.connect(url, row_factory=dict_row, sslmode=sslmode,
                                   prepare_threshold=None, connect_timeout=10)

    def execute(self, sql: str, params=()):
        sql = sql.strip()
        pragma = re.fullmatch(r"PRAGMA table_info\((\w+)\)", sql, re.I)
        if pragma:
            sql = ("SELECT column_name AS name FROM information_schema.columns "
                   "WHERE table_schema='public' AND table_name=%s ORDER BY ordinal_position")
            params = (pragma.group(1),)
        elif sql.upper() == "SELECT LAST_INSERT_ROWID()":
            sql = "SELECT LASTVAL()"
        else:
            ignore = re.match(r"INSERT\s+OR\s+IGNORE\s+INTO\s+", sql, re.I)
            if ignore:
                sql = re.sub(r"^INSERT\s+OR\s+IGNORE\s+INTO\s+", "INSERT INTO ", sql, flags=re.I)
                sql += " ON CONFLICT DO NOTHING"
            sql = sql.replace("%", "%%").replace("?", "%s")
        cursor = self.raw.execute(sql, params)
        lastrowid = None
        if re.match(r"INSERT\s+INTO\s+prospect_drafts\b", sql, re.I):
            lastrowid = self.raw.execute("SELECT LASTVAL()").fetchone()["lastval"]
        return Result(cursor, lastrowid)

    def executescript(self, script: str):
        # Schema creation and seeding share this transaction across cold starts.
        self.raw.execute("SELECT pg_advisory_xact_lock(6404012016)")
        script = re.sub(r"\bid INTEGER PRIMARY KEY AUTOINCREMENT\b",
                        "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", script, flags=re.I)
        script = re.sub(r"\bid INTEGER PRIMARY KEY\b",
                        "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", script, flags=re.I)
        script = re.sub(r"\blead_id INTEGER\b", "lead_id BIGINT", script, flags=re.I)
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()
